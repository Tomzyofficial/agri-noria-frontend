export const NIGERIA_STATE_LIST = Object.keys(NIGERIA_STATES_DATA);

// Resolve raw (lat, lng) coordinates to the closest Nigerian State, Region & default LGA
// so farmers NEVER see confusing raw numbers like "Farm Gate (9.5249, 9.8438)"
export function resolveStateFromCoords(lat, lng) {
  const numLat = parseFloat(lat);
  const numLng = parseFloat(lng);
  if (!isFinite(numLat) || !isFinite(numLng)) {
    return null;
  }

  let closestState = "Kaduna";
  let minDistanceSq = Infinity;

  for (const [stateName, info] of Object.entries(NIGERIA_STATES_DATA)) {
    const dLat = numLat - info.lat;
    const dLng = numLng - info.lng;
    const distSq = dLat * dLat + dLng * dLng;
    if (distSq < minDistanceSq) {
      minDistanceSq = distSq;
      closestState = stateName;
    }
  }

  const matched = NIGERIA_STATES_DATA[closestState];
  return {
    state: closestState,
    region: matched.region,
    lga: matched.lgas[0] || "",
  };
}

// Parse an existing text address into State, Region, LGA, and Landmark if possible
export function parseAddressIntoStructured(addressStr, lat, lng) {
  const cleanAddr =
    addressStr && !/^\s*farm\s*gate\s*\([0-9.,\s-]+\)/i.test(String(addressStr))
      ? String(addressStr).trim()
      : "";

  if (cleanAddr) {
    const lower = cleanAddr.toLowerCase();
    for (const [stateName, info] of Object.entries(NIGERIA_STATES_DATA)) {
      if (lower.includes(stateName.toLowerCase())) {
        const matchedLga =
          info.lgas.find((l) => lower.includes(l.toLowerCase())) || info.lgas[0] || "";
        return {
          state: stateName,
          region: info.region,
          lga: matchedLga,
          landmark: cleanAddr,
        };
      }
    }
  }

  const fromCoords = resolveStateFromCoords(lat, lng);
  if (fromCoords) {
    return {
      state: fromCoords.state,
      region: fromCoords.region,
      lga: fromCoords.lga,
      landmark: cleanAddr || "",
    };
  }

  return {
    state: "Kaduna",
    region: NIGERIA_STATES_DATA.Kaduna.region,
    lga: "Zaria",
    landmark: cleanAddr || "",
  };
}

// Reverse-geocode phone GPS coordinates into plain human-readable State, LGA, Region & Village
export async function reverseGeocodePlainLocation(lat, lng) {
  const fallback = resolveStateFromCoords(lat, lng) || {
    state: "Kaduna",
    region: "North-West Grain Corridor",
    lga: "Zaria",
  };

  try {
    const res = await fetch(
      `https://nominatim.openstreetmap.org/reverse?format=json&lat=${encodeURIComponent(
        lat
      )}&lon=${encodeURIComponent(lng)}&zoom=14&addressdetails=1`,
      { headers: { Accept: "application/json" } }
    );
    if (!res.ok) throw new Error("Nominatim lookup failed");
    const data = await res.json();
    const addr = data?.address || {};

    const rawState = String(addr.state || "").replace(/\s+state$/i, "").trim();
    const matchedState =
      NIGERIA_STATE_LIST.find(
        (s) =>
          s.toLowerCase() === rawState.toLowerCase() ||
          rawState.toLowerCase().includes(s.toLowerCase())
      ) || fallback.state;

    const stateInfo = NIGERIA_STATES_DATA[matchedState] || NIGERIA_STATES_DATA[fallback.state];
    const rawLga =
      addr.county || addr.municipality || addr.city_district || addr.town || addr.city || "";
    const cleanedLga = String(rawLga).replace(/\s+local government area$/i, "").trim();

    const matchedLga =
      stateInfo.lgas.find(
        (l) =>
          l.toLowerCase() === cleanedLga.toLowerCase() ||
          cleanedLga.toLowerCase().includes(l.toLowerCase())
      ) ||
      cleanedLga ||
      stateInfo.lgas[0];

    const villageOrSuburb =
      addr.village || addr.hamlet || addr.suburb || addr.neighbourhood || addr.road || "";

    return {
      state: matchedState,
      region: addr.state_district || stateInfo.region,
      lga: matchedLga,
      landmark: villageOrSuburb || `${matchedLga} Farm Gate`,
    };
  } catch {
    return {
      state: fallback.state,
      region: fallback.region,
      lga: fallback.lga,
      landmark: `${fallback.lga} Farm Area`,
    };
  }
}

